using System.Runtime.InteropServices;

namespace SackMix.Audio;

// Core Audio (mmdeviceapi.h, audiopolicy.h, endpointvolume.h): only what SackMix calls.
// Methods are in vtable order; trailing ones that are never called are left out.
// Windows BOOLs need [MarshalAs(UnmanagedType.Bool)]: COM interop would send a 2-byte VARIANT_BOOL.

internal enum EDataFlow { Render, Capture, All }
internal enum ERole { Console, Multimedia, Communications }
internal enum SessionState { Inactive, Active, Expired }

[StructLayout(LayoutKind.Sequential)]
internal struct PropertyKey(Guid fmtid, int pid)
{
    public Guid Fmtid = fmtid;
    public int Pid = pid;
}

[StructLayout(LayoutKind.Sequential)]
internal struct PropVariant
{
    public ushort Vt;
    private ushort _r1, _r2, _r3;
    public IntPtr P;
    private IntPtr _p2;

    public readonly string? AsString() => Vt == 31 /* VT_LPWSTR */ ? Marshal.PtrToStringUni(P) : null;

    [DllImport("ole32.dll")]
    public static extern int PropVariantClear(ref PropVariant value);
}

